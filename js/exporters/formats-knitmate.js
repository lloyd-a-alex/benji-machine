/**
 * KNITCAT — KnitMate two-bed punch-map format (browser-free, pure).
 *
 * KNITCAT already speaks two double-bed dialects: the boolean single-bed card
 * (`compiler/backends/punchcard.js`) and the Passap E6000 interleaved Front/Back
 * bit pattern (`exporters/formats-passap.js`). The Passap card can only ever express
 * *exactly one* bed punched per needle, because it writes two complementary bit rows.
 * Real double-bed machines — Passap Duos, SRUs, and a single bed run as a ribber —
 * have a fourth state that Passap cannot carry: a needle that is punched on **both**
 * beds at once (a full-family e-print / piqué stitch) or on **neither** (a dropped
 * needle). KnitMate is the format that models all four needle states honestly, one
 * character per needle, one compact row per card line, so a hand-edited or camera-read
 * card survives the round trip instead of collapsing to a binary choice.
 *
 * The per-needle alphabet (see {@link KNITMATE_CHARS}):
 *   `F` front bed only  — colour A sits on the main bed
 *   `B` back bed only    — colour B sits on the ribber (a stranded double-bed stitch)
 *   `X` both beds        — a full-family punch, both carriages take the needle
 *   `_` neither bed      — the needle is dropped / not in working position
 *
 * Because a normal colour chart is binary (a cell is either colour A or colour B), the
 * exporter maps falsy → `F` and truthy → `B`; a card generated by KNITCAT therefore
 * round-trips byte-for-byte through {@link knitMatePatternToMatrix}. A card authored by
 * hand with `X`/`_` still imports: `X` and `B` both read as colour B, `_` and `F` both
 * read as colour A, and the reader warns that it flattened four states onto two so a
 * knitter is never silently handed a lossy chart.
 *
 * The Passap format reads the back bed in the opposite direction to the front; some
 * double-bed cards are also fed end-for-end. {@link generateKnitMatePattern} records a
 * `MIRROR=yes` flag (a whole-row reversal, which for a combined per-needle encoding is
 * the honest equivalent) and the reader undoes it, reproducing the source chart.
 *
 * The text is line-oriented to match the house style of every other KNITCAT format
 * (`AYAB_FORMAT_V1`, `[DESIGNAKNIT_STITCH_PATTERN]`, `*PASSAP_E6000_PATTERN`): a magic
 * tag, a `KEY=value` header, a `DATA=` block written TOP row first so it reads like a
 * printed card, then `*END`. Nothing here touches the DOM and no function throws on
 * malformed input — the worst case is a graceful `{ ok:false, error }`.
 *
 * @module exporters/formats-knitmate
 */

import { logger } from '../core/logging.js';

const log = logger('exporters/formats-knitmate');

const round = Math.round;

/** Truthy matrix cell (colour B) → back bed; falsy (colour A) → front bed. */
const bool = v => (Array.isArray(v) ? v.some(bool) : !!v && v !== 0 && v !== '0');

/**
 * The four needle states, each with the char that encodes it and which beds it punches.
 * Exported so the reader and the tests share one definition and can never drift.
 * @type {{char:string, front:boolean, back:boolean, label:string}[]}
 */
export const KNITMATE_CHARS = Object.freeze([
  { char: 'F', front: true, back: false, label: 'front bed only' },
  { char: 'B', front: false, back: true, label: 'back bed only' },
  { char: 'X', front: true, back: true, label: 'both beds (full family)' },
  { char: '_', front: false, back: false, label: 'neither bed (dropped)' }
]);

/** char → {front,back}, built once from {@link KNITMATE_CHARS}. */
const CHAR_TO_BEDS = Object.freeze(
  KNITMATE_CHARS.reduce((m, e) => ((m[e.char] = { front: e.front, back: e.back }), m), {})
);

/**
 * Encode one colour-matrix cell as a KnitMate needle char. A truthy cell (colour B) is a
 * back-bed punch; a falsy cell (colour A) is a front-bed punch. Optional `both` / `none`
 * overrides let a caller lay in the two states a binary chart cannot express.
 * @param {*} cell @param {{both?:boolean, none?:boolean}} [needle]
 * @returns {'F'|'B'|'X'|'_'}
 */
export function knitMatePunchForCell(cell, needle = {}) {
  if (needle.both) return 'X';
  if (needle.none) return '_';
  return bool(cell) ? 'B' : 'F';
}

/**
 * Decode one KnitMate row string into per-needle bed booleans. Unknown characters are
 * reported via the `unknown` count rather than thrown away silently.
 * @param {string} line a string of `F`/`B`/`X`/`_` (case-insensitive, other chars ignored)
 * @returns {{front:number[], back:number[], chars:string[], unknown:number}}
 */
export function parseKnitMateRow(line) {
  const chars = [];
  const front = [];
  const back = [];
  let unknown = 0;
  for (const raw of String(line == null ? '' : line)) {
    const ch = raw.toUpperCase();
    const beds = CHAR_TO_BEDS[ch];
    if (!beds) { if (/\S/.test(raw)) unknown++; continue; }
    chars.push(ch);
    front.push(beds.front ? 1 : 0);
    back.push(beds.back ? 1 : 0);
  }
  return { front, back, chars, unknown };
}

/** Reverse a row for a mirror-fed card; returns a fresh array. */
function mirrorRow(arr, mirror) {
  return mirror ? arr.slice().reverse() : arr.slice();
}

/**
 * Build the full two-bed structure for a colour matrix.
 *
 * @param {Array<Array<*>>} cardMatrix rows bottom-first (editor order), cell truthy = colour B
 * @param {object} [opts] { mirror?:boolean, bothAt?:(r,c)=>boolean, noneAt?:(r,c)=>boolean }
 * @returns {{width:number, height:number, mirror:boolean, rows:Array<{index:number, chars:string, front:number[], back:number[]}>}}
 */
export function buildKnitMateBeds(cardMatrix, opts = {}) {
  const matrix = Array.isArray(cardMatrix) ? cardMatrix : [];
  const height = matrix.length;
  const width = matrix.reduce((m, r) => Math.max(m, (r || []).length), 0);
  const mirror = !!opts.mirror;
  const rows = [];
  // Emit TOP row first (index height-1 … 0) so the printed card reads the way you look at it.
  for (let r = height - 1; r >= 0; r--) {
    const src = matrix[r] || [];
    const chars = new Array(width);
    const front = new Array(width);
    const back = new Array(width);
    for (let c = 0; c < width; c++) {
      const needle = {};
      // Four-state hooks: a caller can inject both/none needles the chart itself cannot say.
      if (typeof opts.bothAt === 'function' && opts.bothAt(r, c)) needle.both = true;
      else if (typeof opts.noneAt === 'function' && opts.noneAt(r, c)) needle.none = true;
      const ch = knitMatePunchForCell(src[c], needle);
      chars[c] = ch;
      const beds = CHAR_TO_BEDS[ch];
      front[c] = beds.front ? 1 : 0;
      back[c] = beds.back ? 1 : 0;
    }
    rows.push({
      index: r,
      chars: mirrorRow(chars, mirror).join(''),
      front: mirrorRow(front, mirror),
      back: mirrorRow(back, mirror)
    });
  }
  return { width, height, mirror, rows };
}

/**
 * Generate the KnitMate two-bed punch-map text.
 *
 * @param {Array<Array<*>>} cardMatrix
 * @param {object} [opts] { title?:string, mirror?:boolean, bothAt?:Function, noneAt?:Function }
 * @returns {string}
 */
export function generateKnitMatePattern(cardMatrix, opts = {}) {
  const { width, height, mirror, rows } = buildKnitMateBeds(cardMatrix, opts);
  if (!width || !height) log.warn('generated a KnitMate card from an empty chart — the export carries only a header', { width, height });
  const lines = [];
  lines.push('*KNITMATE_CARD_V1');
  lines.push(`NAME=${String(opts.title || 'KNITCAT').replace(/[\r\n=]/g, ' ').trim()}`);
  lines.push(`WIDTH=${width}`);
  lines.push(`HEIGHT=${height}`);
  lines.push('BEDS=2');
  lines.push('ENCODING=FBX_');
  lines.push(`MIRROR=${mirror ? 'yes' : 'no'}`);
  lines.push('COLOR_MAP=double-bed-4-state');
  lines.push('DATA=');
  for (const row of rows) lines.push(row.chars);
  lines.push('*END');
  return lines.join('\n');
}

/**
 * Convert a KnitMate punch-map back to a single-bed colour matrix (cell 1 = colour B /
 * back bed, cell 0 = colour A / front bed). Shared by {@link module:importers/knitmate-import}
 * and the tests so the write and read mappings can never disagree.
 *
 * @param {string} text the pattern produced by {@link generateKnitMatePattern}
 * @returns {{ok:boolean, matrix?:number[][], warnings?:string[], error?:string}}
 */
export function knitMatePatternToMatrix(text) {
  const raw = String(text || '').split(/\r?\n/);
  if (!raw.some(l => l.trim() === '*KNITMATE_CARD_V1')) {
    return { ok: false, error: 'Not a KnitMate card (missing the *KNITMATE_CARD_V1 tag).' };
  }
  const header = {};
  for (const line of raw) {
    const m = /^([A-Z_]+)=(.*)$/.exec(line.trim());
    if (m) header[m[1]] = m[2].trim();
  }
  const width = parseInt(header.WIDTH, 10);
  const mirror = /^yes$/i.test(header.MIRROR || '');
  const warnings = [];

  const dataStart = raw.findIndex(l => l.trim() === 'DATA=');
  if (dataStart < 0) return { ok: false, error: 'The KnitMate card has no DATA= block.' };
  const topFirst = [];
  let sawFourStates = false;
  let unknownChars = 0;
  for (let i = dataStart + 1; i < raw.length; i++) {
    const line = raw[i];
    const t = line.trim();
    if (t === '*END') break;
    if (!t) continue;
    if (/^([A-Z_]+=.*)$/.test(t)) continue; // stray header-looking commentary
    const parsed = parseKnitMateRow(t);
    if (parsed.chars.some(ch => ch === 'X' || ch === '_')) sawFourStates = true;
    unknownChars += parsed.unknown;
    // A row with no recognised needle codes at all is skipped, not padded to zero width.
    if (!parsed.chars.length) continue;
    topFirst.push({ front: parsed.front, back: parsed.back });
  }
  if (!topFirst.length) return { ok: false, error: 'The KnitMate DATA block held no rows.' };
  if (unknownChars > 0) {
    warnings.push(`${unknownChars} unrecognised character(s) in the DATA block were ignored.`);
  }

  const bottomFirst = topFirst.slice().reverse();
  const matrix = bottomFirst.map(row => {
    const back = mirror ? row.back.slice().reverse() : row.back;
    return back.map(b => (b ? 1 : 0));
  });
  const maxW = matrix.reduce((m, r) => Math.max(m, r.length), 0);
  if (Number.isFinite(width) && width !== maxW) {
    warnings.push(`Header declares ${width} needles but the data is ${maxW} wide. Believed the data.`);
  }
  for (const row of matrix) while (row.length < maxW) row.push(0);

  if (sawFourStates) {
    warnings.push('This card uses the four-state alphabet (X = both beds, _ = dropped); a single-bed colour chart flattens both→back and none→front.');
  }
  return { ok: true, matrix, warnings };
}

/**
 * A compact statistics summary the export toast / docs can show.
 * @param {Array<Array<*>>} cardMatrix
 * @param {object} [opts]
 * @returns {{beds:number, width:number, height:number, frontPunches:number, backPunches:number, bothPunches:number, blankNeedles:number, totalPunches:number, rows:number}}
 */
export function knitMateSummary(cardMatrix, opts = {}) {
  const { width, height, rows } = buildKnitMateBeds(cardMatrix, opts);
  let frontPunches = 0;
  let backPunches = 0;
  let bothPunches = 0;
  let blankNeedles = 0;
  for (const r of rows) {
    for (let c = 0; c < r.front.length; c++) {
      const f = r.front[c];
      const b = r.back[c];
      if (f && b) bothPunches++;
      else if (f) frontPunches++;
      else if (b) backPunches++;
      else blankNeedles++;
    }
  }
  return {
    beds: 2, width, height, rows: round(height),
    frontPunches, backPunches, bothPunches, blankNeedles,
    totalPunches: frontPunches + backPunches + bothPunches
  };
}
